#[test]
fn drops_with_cascade_and_renames_from_the_tree() {
    let r = DropRequest {
        schema: "shop".into(),
        name: "users".into(),
        kind: "table".into(),
        cascade: true,
        referencing: vec![Referencing {
            schema: "shop".into(),
            table: "orders".into(),
            constraint: "orders_user_fk".into(),
        }],
        ..Default::default()
    };
    assert_eq!(drop_statements(Dialect::Postgres, &r), vec!["DROP TABLE \"shop\".\"users\" CASCADE;"]);
    assert_eq!(
        drop_statements(Dialect::MySql, &r),
        vec![
            "ALTER TABLE `shop`.`orders` DROP FOREIGN KEY `orders_user_fk`;",
            "DROP TABLE `shop`.`users`;",
        ]
    );
    assert_eq!(
        drop_statements(Dialect::Oracle, &r),
        vec!["DROP TABLE \"shop\".\"users\" CASCADE CONSTRAINTS;"]
    );
    let v = DropRequest {
        kind: "matview".into(),
        if_exists: true,
        ..r.clone()
    };
    assert_eq!(
        drop_statements(Dialect::Postgres, &v),
        vec!["DROP MATERIALIZED VIEW IF EXISTS \"shop\".\"users\" CASCADE;"]
    );
    assert_eq!(
        rename_table(Dialect::SqlServer, "dbo", "users", "people"),
        "EXEC sp_rename N'dbo.users', N'people';"
    );
    assert_eq!(
        rename_table(Dialect::MySql, "shop", "users", "people"),
        "RENAME TABLE `shop`.`users` TO `shop`.`people`;"
    );
    assert_eq!(
        rename_column(Dialect::Postgres, "public", "users", "mail", "email"),
        "ALTER TABLE \"public\".\"users\" RENAME COLUMN \"mail\" TO \"email\";"
    );
}

#[test]
fn spec_from_introspected_table() {
    let t = TableInfo {
        name: "users".into(),
        columns: vec![ColumnInfo {
            name: "id".into(),
            data_type: "bigint".into(),
            auto_increment: true,
            ..Default::default()
        }],
        primary_key: vec!["id".into()],
        indexes: vec![
            IndexInfo {
                name: "users_pkey".into(),
                columns: vec!["id".into()],
                unique: true,
                primary: true,
            },
            IndexInfo {
                name: "users_email_unique".into(),
                columns: vec!["email".into()],
                unique: true,
                primary: false,
            },
        ],
        ..Default::default()
    };
    let s = TableSpec::from_table("public", &t);
    assert_eq!(s.columns[0].original.as_deref(), Some("id"));
    assert_eq!(s.primary_key.unwrap().name, "users_pkey");
    assert_eq!(s.unique_keys[0].name, "users_email_unique");
    assert!(s.indexes.is_empty());
}

