use super::*;
use crate::model::{CheckInfo, ColumnInfo, ForeignKey, IndexInfo, TableInfo};

fn col(name: &str, ty: &str, nullable: bool) -> ColumnSpec {
    ColumnSpec {
        original: None,
        name: name.into(),
        data_type: ty.into(),
        nullable,
        ..Default::default()
    }
}

/// `orders (id auto-increment PK, user_id FK → users, total with a check, note comment)`.
fn orders(d: Dialect) -> TableSpec {
    let int = if d == Dialect::Oracle { "NUMBER(19)" } else { "bigint" };
    TableSpec {
        schema: "shop".into(),
        name: "orders".into(),
        comment: "Customer orders".into(),
        columns: vec![
            ColumnSpec {
                auto_increment: true,
                ..col("id", int, false)
            },
            col("user_id", int, false),
            ColumnSpec {
                default: Some("0".into()),
                ..col("total", "decimal(10,2)", false)
            },
            ColumnSpec {
                comment: "Free text".into(),
                ..col("note", "varchar(200)", true)
            },
        ],
        primary_key: Some(KeySpec {
            name: "orders_pk".into(),
            columns: vec!["id".into()],
        }),
        unique_keys: vec![],
        foreign_keys: vec![ForeignKey {
            name: "orders_user_fk".into(),
            columns: vec!["user_id".into()],
            ref_schema: "shop".into(),
            ref_table: "users".into(),
            ref_columns: vec!["id".into()],
            on_delete: "cascade".into(),
            ..Default::default()
        }],
        indexes: vec![IndexSpec {
            name: "orders_user_idx".into(),
            columns: vec!["user_id".into()],
            ..Default::default()
        }],
        checks: vec![CheckInfo {
            name: "orders_total_ck".into(),
            expression: "total >= 0".into(),
        }],
        options: TableOptions::default(),
    }
}

#[test]
fn creates_mysql_table_with_options() {
    let mut t = orders(Dialect::MySql);
    t.options.engine = "InnoDB".into();
    t.options.charset = "utf8mb4".into();
    let sql = create_table(Dialect::MySql, &t, CreateOptions { if_not_exists: true });
    assert_eq!(
        sql,
        "CREATE TABLE IF NOT EXISTS `shop`.`orders`\n(\n    `id` bigint AUTO_INCREMENT NOT NULL,\n    `user_id` bigint NOT NULL,\n    `total` decimal(10,2) DEFAULT 0 NOT NULL,\n    `note` varchar(200) COMMENT 'Free text',\n    CONSTRAINT `orders_pk` PRIMARY KEY (`id`),\n    CONSTRAINT `orders_user_fk` FOREIGN KEY (`user_id`) REFERENCES `shop`.`users` (`id`) ON DELETE CASCADE,\n    CONSTRAINT `orders_total_ck` CHECK (total >= 0)\n) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = 'Customer orders';\n\nCREATE INDEX `orders_user_idx` ON `shop`.`orders` (`user_id`);\n"
    );
}

#[test]
fn creates_postgres_table_with_identity_and_comments() {
    let mut t = orders(Dialect::Postgres);
    t.options.unlogged = true;
    t.indexes[0].method = "btree".into();
    let sql = create_table(Dialect::Postgres, &t, CreateOptions::default());
    assert!(sql.starts_with("CREATE UNLOGGED TABLE \"shop\".\"orders\"\n(\n    \"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,"));
    assert!(sql.contains("CREATE INDEX \"orders_user_idx\" ON \"shop\".\"orders\" USING btree (\"user_id\");"));
    assert!(sql.contains("COMMENT ON TABLE \"shop\".\"orders\" IS 'Customer orders';"));
    assert!(sql.contains("COMMENT ON COLUMN \"shop\".\"orders\".\"note\" IS 'Free text';"));
    // Serial types generate values themselves.
    let mut s = orders(Dialect::Postgres);
    s.columns[0].data_type = "bigserial".into();
    assert!(create_table(Dialect::Postgres, &s, CreateOptions::default()).contains("\"id\" bigserial NOT NULL,"));
}

#[test]
fn creates_sqlite_sqlserver_oracle_and_clickhouse_tables() {
    let mut t = orders(Dialect::Sqlite);
    t.schema = "main".into();
    t.columns[0].data_type = "INTEGER".into();
    t.options.strict = true;
    let sql = create_table(Dialect::Sqlite, &t, CreateOptions::default());
    assert!(sql.contains("\"id\" INTEGER PRIMARY KEY AUTOINCREMENT,"));
    assert!(!sql.contains("CONSTRAINT \"orders_pk\""));
    assert!(sql.contains(") STRICT;"));
    assert!(!sql.contains("COMMENT"));

    let t = orders(Dialect::SqlServer);
    let sql = create_table(Dialect::SqlServer, &t, CreateOptions { if_not_exists: true });
    assert!(sql.starts_with("IF OBJECT_ID(N'[shop].[orders]', N'U') IS NULL\nCREATE TABLE [shop].[orders]"));
    assert!(sql.contains("[id] bigint IDENTITY(1,1) NOT NULL,"));
    assert!(sql.contains("[note] varchar(200) NULL"));
    assert!(sql.contains("EXEC sp_addextendedproperty N'MS_Description', N'Free text', N'SCHEMA', N'shop', N'TABLE', N'orders', N'COLUMN', N'note';"));

    let t = orders(Dialect::Oracle);
    let sql = create_table(Dialect::Oracle, &t, CreateOptions { if_not_exists: true });
    assert!(sql.starts_with("CREATE TABLE \"shop\".\"orders\""), "{sql}");
    assert!(sql.contains("\"id\" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL"));
    assert!(sql.contains("ON DELETE CASCADE"));

    let mut t = orders(Dialect::ClickHouse);
    t.columns[1].data_type = "UInt64".into();
    let sql = create_table(Dialect::ClickHouse, &t, CreateOptions::default());
    assert!(sql.contains("`note` Nullable(varchar(200)) COMMENT 'Free text'"));
    assert!(!sql.contains("FOREIGN KEY"));
    assert!(sql.contains(") ENGINE = MergeTree() ORDER BY `id` COMMENT 'Customer orders';"));
}

fn loaded(d: Dialect) -> TableSpec {
    let mut t = orders(d);
    for c in &mut t.columns {
        c.original = Some(c.name.clone());
    }
    t
}

#[test]
fn alter_renames_drops_adds_and_modifies_postgres() {
    let old = loaded(Dialect::Postgres);
    let mut new = old.clone();
    new.name = "purchases".into();
    new.columns[3].name = "remark".into(); // rename (tracked by original)
    new.columns[2].data_type = "numeric(12,2)".into(); // type change
    new.columns[2].default = None;
    new.columns.remove(1); // drop user_id
    new.foreign_keys.clear();
    new.indexes.clear();
    new.columns.push(col("status", "varchar(20)", false));
    new.columns.last_mut().unwrap().default = Some("'new'".into());
    let plan = alter_table(Dialect::Postgres, &old, &new);
    assert_eq!(
        plan.statements,
        vec![
            "ALTER TABLE \"shop\".\"orders\" RENAME TO \"purchases\";",
            "ALTER TABLE \"shop\".\"purchases\" DROP CONSTRAINT \"orders_user_fk\";",
            "DROP INDEX \"shop\".\"orders_user_idx\";",
            "ALTER TABLE \"shop\".\"purchases\" RENAME COLUMN \"note\" TO \"remark\";",
            "ALTER TABLE \"shop\".\"purchases\" DROP COLUMN \"user_id\";",
            "ALTER TABLE \"shop\".\"purchases\" ADD COLUMN \"status\" varchar(20) DEFAULT 'new' NOT NULL;",
            "ALTER TABLE \"shop\".\"purchases\" ALTER COLUMN \"total\" TYPE numeric(12,2) USING \"total\"::numeric(12,2);",
            "ALTER TABLE \"shop\".\"purchases\" ALTER COLUMN \"total\" DROP DEFAULT;",
        ]
    );
    assert!(plan.destructive());
    let msgs: Vec<_> = plan.warnings.iter().map(|w| w.message.as_str()).collect();
    assert!(msgs.contains(&"Column user_id is dropped with its data"));
    assert!(msgs.iter().any(|m| m.starts_with("Changing total from decimal(10,2) to numeric(12,2)")));
}

#[test]
fn alter_mysql_uses_change_for_renamed_and_modified_columns() {
    let old = loaded(Dialect::MySql);
    let mut new = old.clone();
    new.columns[3].name = "remark".into();
    new.columns[3].data_type = "text".into();
    new.columns[1].comment = "Buyer".into();
    new.checks.clear();
    new.unique_keys.push(KeySpec {
        name: "orders_note_uq".into(),
        columns: vec!["remark".into()],
    });
    new.comment = "All orders".into();
    let plan = alter_table(Dialect::MySql, &old, &new);
    assert_eq!(
        plan.statements,
        vec![
            "ALTER TABLE `shop`.`orders` DROP CHECK `orders_total_ck`;",
            "ALTER TABLE `shop`.`orders` MODIFY COLUMN `user_id` bigint NOT NULL COMMENT 'Buyer';",
            "ALTER TABLE `shop`.`orders` CHANGE COLUMN `note` `remark` text COMMENT 'Free text';",
            "ALTER TABLE `shop`.`orders` ADD CONSTRAINT `orders_note_uq` UNIQUE (`remark`);",
            "ALTER TABLE `shop`.`orders` COMMENT = 'All orders';",
        ]
    );
    assert!(plan.destructive());
}

#[test]
fn alter_without_original_names_pairs_renames_by_position_and_type() {
    let old = orders(Dialect::Postgres);
    let mut new = old.clone();
    new.columns[3].name = "remark".into();
    let plan = alter_table(Dialect::Postgres, &old, &new);
    assert_eq!(
        plan.statements,
        vec!["ALTER TABLE \"shop\".\"orders\" RENAME COLUMN \"note\" TO \"remark\";"]
    );
    assert!(!plan.destructive());
    // A different type at the same position is a drop plus an add.
    new.columns[3].data_type = "integer".into();
    let plan = alter_table(Dialect::Postgres, &old, &new);
    assert_eq!(plan.statements.len(), 3);
    assert!(plan.statements[0].contains("DROP COLUMN \"note\""));
    assert!(plan.statements[1].contains("ADD COLUMN \"remark\" integer"));
    assert!(plan.statements[2].starts_with("COMMENT ON COLUMN \"shop\".\"orders\".\"remark\""));
    assert!(plan.destructive());
}

