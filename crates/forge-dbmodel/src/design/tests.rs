#[test]
fn alter_sqlserver_oracle_and_clickhouse() {
    let old = loaded(Dialect::SqlServer);
    let mut new = old.clone();
    new.columns[3].name = "remark".into();
    new.columns[2].default = Some("1".into());
    new.columns[1].nullable = true;
    new.columns[3].comment = String::new();
    let plan = alter_table(Dialect::SqlServer, &old, &new);
    assert_eq!(plan.statements[0], "EXEC sp_rename N'shop.orders.note', N'remark', N'COLUMN';");
    assert_eq!(plan.statements[1], "ALTER TABLE [shop].[orders] ALTER COLUMN [user_id] bigint NULL;");
    assert!(plan.statements[2].starts_with("DECLARE @df sysname = (SELECT name FROM sys.default_constraints"));
    assert_eq!(plan.statements[3], "ALTER TABLE [shop].[orders] ADD DEFAULT 1 FOR [total];");
    assert_eq!(
        plan.statements[4],
        "EXEC sp_dropextendedproperty N'MS_Description', N'SCHEMA', N'shop', N'TABLE', N'orders', N'COLUMN', N'remark';"
    );

    let old = loaded(Dialect::Oracle);
    let mut new = old.clone();
    new.columns[3].data_type = "VARCHAR2(400)".into();
    new.columns[3].nullable = false;
    new.columns.push(col("status", "VARCHAR2(20)", true));
    let plan = alter_table(Dialect::Oracle, &old, &new);
    assert_eq!(
        plan.statements,
        vec![
            "ALTER TABLE \"shop\".\"orders\" ADD (\"status\" VARCHAR2(20));",
            "ALTER TABLE \"shop\".\"orders\" MODIFY (\"note\" VARCHAR2(400) NOT NULL);",
        ]
    );
    assert!(plan.warnings.iter().any(|w| !w.destructive && w.message.contains("NOT NULL")));

    let old = loaded(Dialect::ClickHouse);
    let mut new = old.clone();
    new.columns[3].comment = "Text".into();
    new.columns[2].data_type = "Decimal(18, 2)".into();
    let plan = alter_table(Dialect::ClickHouse, &old, &new);
    assert_eq!(
        plan.statements,
        vec![
            "ALTER TABLE `shop`.`orders` MODIFY COLUMN `total` Decimal(18, 2) DEFAULT 0;",
            "ALTER TABLE `shop`.`orders` COMMENT COLUMN `note` 'Text';",
        ]
    );
}

#[test]
fn sqlite_renames_in_place_but_rebuilds_for_type_changes() {
    let mut old = loaded(Dialect::Sqlite);
    old.schema = "main".into();
    old.columns[0].data_type = "INTEGER".into();
    let mut new = old.clone();
    new.columns[3].name = "remark".into();
    new.columns.push(col("status", "TEXT", true));
    let plan = alter_table(Dialect::Sqlite, &old, &new);
    assert_eq!(
        plan.statements,
        vec![
            "ALTER TABLE \"orders\" RENAME COLUMN \"note\" TO \"remark\";",
            "ALTER TABLE \"orders\" ADD COLUMN \"status\" TEXT;",
        ]
    );
    new.columns[2].data_type = "REAL".into();
    let plan = alter_table(Dialect::Sqlite, &old, &new);
    assert_eq!(plan.statements[0], "PRAGMA foreign_keys = OFF;");
    assert!(plan.statements[1].starts_with("CREATE TABLE \"orders_new\""));
    assert_eq!(
        plan.statements[2],
        "INSERT INTO \"orders_new\" (\"id\", \"user_id\", \"total\", \"remark\") SELECT \"id\", \"user_id\", \"total\", \"note\" FROM \"orders\";"
    );
    assert_eq!(plan.statements[3], "DROP TABLE \"orders\";");
    assert_eq!(plan.statements[4], "ALTER TABLE \"orders_new\" RENAME TO \"orders\";");
    assert!(plan.statements.iter().any(|s| s.starts_with("CREATE INDEX \"orders_user_idx\"")));
    assert!(plan.destructive());
}

