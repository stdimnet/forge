//! The Create Table and Modify Table dialogs (DataGrip style): a table as the dialogs edit
//! it ([`TableSpec`]), its `CREATE TABLE` script per dialect, the `ALTER` statements that
//! turn an existing table into the edited one ([`alter`], a rename-aware diff with warnings
//! for destructive changes), Drop and Rename from the tree, and what each dialect offers
//! (types for completion, table options) in [`types`].

pub mod alter;
pub mod types;

use forge_sql::Dialect;
use serde::{Deserialize, Serialize};

use crate::model::{CheckInfo, ForeignKey, TableInfo};

pub use alter::{alter_table, AlterPlan, DesignWarning};
pub use types::{dialect_info, DesignDialect, OptionField};

/// A column of the dialogs.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
pub struct ColumnSpec {
    /// The column's name in the database: set for existing columns (Modify Table), so a
    /// changed name is a rename and not a drop plus an add. `None` for new columns.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub original: Option<String>,
    pub name: String,
    pub data_type: String,
    pub nullable: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub default: Option<String>,
    pub comment: String,
    /// `AUTO_INCREMENT`, `IDENTITY`, `GENERATED BY DEFAULT AS IDENTITY`, …
    pub auto_increment: bool,
}

/// A primary or unique key.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
pub struct KeySpec {
    /// Constraint name; empty lets the database choose one.
    pub name: String,
    pub columns: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
pub struct IndexSpec {
    pub name: String,
    pub columns: Vec<String>,
    pub unique: bool,
    /// Index method: `btree`, `hash`, `gin`, … (PostgreSQL and MySQL); empty is the default.
    pub method: String,
}

/// Table options; each dialect uses its own (see [`types::dialect_info`]), empty values
/// keep the database default.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
pub struct TableOptions {
    /// MySQL storage engine (`InnoDB`), ClickHouse table engine (`MergeTree`).
    pub engine: String,
    /// MySQL default character set and collation.
    pub charset: String,
    pub collation: String,
    /// PostgreSQL and Oracle tablespace.
    pub tablespace: String,
    /// PostgreSQL `UNLOGGED`.
    pub unlogged: bool,
    pub temporary: bool,
    /// SQLite `WITHOUT ROWID` and `STRICT`.
    pub without_rowid: bool,
    pub strict: bool,
    /// ClickHouse `ORDER BY` and `PARTITION BY` expressions.
    pub order_by: String,
    pub partition_by: String,
}

/// A table as the Create/Modify Table dialogs edit it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
pub struct TableSpec {
    /// Empty: an unqualified name.
    pub schema: String,
    pub name: String,
    pub comment: String,
    pub columns: Vec<ColumnSpec>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub primary_key: Option<KeySpec>,
    pub unique_keys: Vec<KeySpec>,
    pub foreign_keys: Vec<ForeignKey>,
    pub indexes: Vec<IndexSpec>,
    pub checks: Vec<CheckInfo>,
    pub options: TableOptions,
}

impl TableSpec {
    /// The dialog's model of an existing table: every column remembers its name, so the
    /// diff sees renames.
    pub fn from_table(schema: &str, t: &TableInfo) -> Self {
        let pk_index = t.indexes.iter().find(|i| i.primary);
        TableSpec {
            schema: schema.to_string(),
            name: t.name.clone(),
            comment: t.comment.clone(),
            columns: t
                .columns
                .iter()
                .filter(|c| !c.is_virtual)
                .map(|c| ColumnSpec {
                    original: Some(c.name.clone()),
                    name: c.name.clone(),
                    data_type: c.data_type.clone(),
                    nullable: c.nullable,
                    default: c.default.clone(),
                    comment: c.comment.clone(),
                    auto_increment: c.auto_increment,
                })
                .collect(),
            primary_key: (!t.primary_key.is_empty()).then(|| KeySpec {
                name: pk_index.map(|i| i.name.clone()).unwrap_or_default(),
                columns: t.primary_key.clone(),
            }),
            unique_keys: t
                .indexes
                .iter()
                .filter(|i| i.unique && !i.primary)
                .map(|i| KeySpec {
                    name: i.name.clone(),
                    columns: i.columns.clone(),
                })
                .collect(),
            foreign_keys: t
                .foreign_keys
                .iter()
                .filter(|f| !f.is_virtual)
                .cloned()
                .collect(),
            indexes: t
                .indexes
                .iter()
                .filter(|i| !i.unique && !i.primary)
                .map(|i| IndexSpec {
                    name: i.name.clone(),
                    columns: i.columns.clone(),
                    unique: false,
                    method: String::new(),
                })
                .collect(),
            checks: t.checks.clone(),
            options: TableOptions::default(),
        }
    }

    pub fn column(&self, name: &str) -> Option<&ColumnSpec> {
        self.columns
            .iter()
            .find(|c| c.name.eq_ignore_ascii_case(name))
    }

    /// The single auto-increment primary key column SQLite writes inline
    /// (`INTEGER PRIMARY KEY AUTOINCREMENT`).
    fn sqlite_rowid_pk(&self) -> Option<&ColumnSpec> {
        let pk = self.primary_key.as_ref()?;
        match pk.columns.as_slice() {
            [one] => self.column(one).filter(|c| c.auto_increment),
            _ => None,
        }
    }
}

/// Options of the generated `CREATE` statements.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct CreateOptions {
    pub if_not_exists: bool,
}

pub(crate) fn cols(d: Dialect, cs: &[String]) -> String {
    cs.iter()
        .map(|c| d.quote_ident(c))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The type a column is written with: ClickHouse wraps nullable types.
pub(crate) fn column_type(d: Dialect, c: &ColumnSpec) -> String {
    let ty = c.data_type.trim();
    let ty = if ty.is_empty() { "varchar(255)" } else { ty };
    if d == Dialect::ClickHouse && c.nullable && !ty.starts_with("Nullable(") {
        format!("Nullable({ty})")
    } else {
        ty.to_string()
    }
}

/// PostgreSQL serial types and `nextval(…)` defaults already generate values.
pub(crate) fn implicit_identity(d: Dialect, c: &ColumnSpec) -> bool {
    let ty = c.data_type.to_ascii_lowercase();
    d == Dialect::Postgres
        && (ty.ends_with("serial")
            || c.default
                .as_deref()
                .is_some_and(|v| v.trim_start().starts_with("nextval(")))
}

/// The identity clause of an auto-increment column.
pub(crate) fn identity_clause(d: Dialect, c: &ColumnSpec) -> Option<&'static str> {
    if !c.auto_increment || implicit_identity(d, c) {
        return None;
    }
    match d {
        Dialect::MySql => Some("AUTO_INCREMENT"),
        Dialect::Postgres | Dialect::Oracle => Some("GENERATED BY DEFAULT AS IDENTITY"),
        Dialect::SqlServer => Some("IDENTITY(1,1)"),
        _ => None,
    }
}

/// `"name" type NOT NULL DEFAULT … COMMENT …` (the full definition, as MySQL's
/// `MODIFY COLUMN` needs it).
pub(crate) fn column_def(d: Dialect, c: &ColumnSpec, inline_pk: bool) -> String {
    let mut l = format!("{} {}", d.quote_ident(&c.name), column_type(d, c));
    if inline_pk {
        // SQLite's rowid alias.
        return format!("{l} PRIMARY KEY AUTOINCREMENT");
    }
    let identity = identity_clause(d, c);
    if let Some(def) = c.default.as_deref().filter(|v| !v.trim().is_empty()) {
        if identity.is_none() || d == Dialect::MySql {
            // Oracle and SQL Server write the default before the constraints too.
            l.push_str(&format!(" DEFAULT {}", def.trim()));
        }
    }
    if let Some(id) = identity {
        l.push(' ');
        l.push_str(id);
    }
    match d {
        Dialect::ClickHouse => {}
        _ if !c.nullable => l.push_str(" NOT NULL"),
        Dialect::SqlServer => l.push_str(" NULL"),
        _ => {}
    }
    if !c.comment.is_empty() && matches!(d, Dialect::MySql | Dialect::ClickHouse) {
        l.push_str(&format!(" COMMENT {}", d.quote_str(&c.comment)));
    }
    l
}

fn constraint(d: Dialect, name: &str, body: String) -> String {
    if name.is_empty() {
        body
    } else {
        format!("CONSTRAINT {} {body}", d.quote_ident(name))
    }
}

pub(crate) fn pk_clause(d: Dialect, k: &KeySpec) -> String {
    constraint(d, &k.name, format!("PRIMARY KEY ({})", cols(d, &k.columns)))
}

pub(crate) fn unique_clause(d: Dialect, k: &KeySpec) -> String {
    constraint(d, &k.name, format!("UNIQUE ({})", cols(d, &k.columns)))
}

pub(crate) fn check_clause(d: Dialect, c: &CheckInfo) -> String {
    let expr = c.expression.trim();
    let expr = if expr.starts_with('(') && expr.ends_with(')') {
        expr.to_string()
    } else {
        format!("({expr})")
    };
    constraint(d, &c.name, format!("CHECK {expr}"))
}

pub(crate) fn fk_clause(d: Dialect, f: &ForeignKey) -> String {
    let mut l = constraint(
        d,
        &f.name,
        format!(
            "FOREIGN KEY ({}) REFERENCES {} ({})",
            cols(d, &f.columns),
            d.qualified(&f.ref_schema, &f.ref_table),
            cols(d, &f.ref_columns)
        ),
    );
    let action = |a: &str| !a.is_empty() && !a.eq_ignore_ascii_case("NO ACTION");
    // Oracle has no ON UPDATE.
    if action(&f.on_update) && d != Dialect::Oracle {
        l.push_str(&format!(" ON UPDATE {}", f.on_update.to_ascii_uppercase()));
    }
    if action(&f.on_delete) {
        l.push_str(&format!(" ON DELETE {}", f.on_delete.to_ascii_uppercase()));
    }
    l
}

pub(crate) fn create_index(d: Dialect, table: &str, schema: &str, i: &IndexSpec, ine: bool) -> String {
    let unique = if i.unique { "UNIQUE " } else { "" };
    let ine = if ine && supports_if_not_exists(d, "index") {
        "IF NOT EXISTS "
    } else {
        ""
    };
    let name = d.quote_ident(&i.name);
    let target = d.qualified(schema, table);
    let method = i.method.trim();
    match d {
        Dialect::Postgres if !method.is_empty() => format!(
            "CREATE {unique}INDEX {ine}{name} ON {target} USING {method} ({});",
            cols(d, &i.columns)
        ),
        Dialect::MySql if !method.is_empty() => format!(
            "CREATE {unique}INDEX {name} ON {target} ({}) USING {};",
            cols(d, &i.columns),
            method.to_ascii_uppercase()
        ),
        _ => format!(
            "CREATE {unique}INDEX {ine}{name} ON {target} ({});",
            cols(d, &i.columns)
        ),
    }
}

/// Whether `CREATE <kind> IF NOT EXISTS` is accepted (`table`, `index`, `sequence`, `view`).
pub fn supports_if_not_exists(d: Dialect, kind: &str) -> bool {
    match (d, kind) {
        (Dialect::Oracle | Dialect::SqlServer, _) => false,
        (Dialect::MySql, "index" | "sequence") => false,
        (Dialect::Sqlite, "sequence") => false,
        (Dialect::Postgres, "view") => false,
        _ => true,
    }
}

pub(crate) fn sqlserver_comment(
    schema: &str,
    table: &str,
    column: Option<&str>,
    comment: &str,
    proc_name: &str,
) -> String {
    let d = Dialect::SqlServer;
    let schema = if schema.is_empty() { "dbo" } else { schema };
    let mut s = format!("EXEC {proc_name} N'MS_Description', ");
    if proc_name != "sp_dropextendedproperty" {
        s.push_str(&format!("{}, ", d.quote_str(comment)));
    }
    s.push_str(&format!(
        "N'SCHEMA', {}, N'TABLE', {}",
        d.quote_str(schema),
        d.quote_str(table)
    ));
    if let Some(c) = column {
        s.push_str(&format!(", N'COLUMN', {}", d.quote_str(c)));
    }
    s.push(';');
    s
}

/// Comments of a new table and its columns as separate statements (PostgreSQL, Oracle and
/// SQL Server keep them outside `CREATE TABLE`).
fn comment_statements(d: Dialect, t: &TableSpec) -> Vec<String> {
    let name = d.qualified(&t.schema, &t.name);
    let mut out = Vec::new();
    match d {
        Dialect::Postgres | Dialect::Oracle => {
            if !t.comment.is_empty() {
                out.push(format!(
                    "COMMENT ON TABLE {name} IS {};",
                    d.quote_str(&t.comment)
                ));
            }
            for c in t.columns.iter().filter(|c| !c.comment.is_empty()) {
                out.push(format!(
                    "COMMENT ON COLUMN {name}.{} IS {};",
                    d.quote_ident(&c.name),
                    d.quote_str(&c.comment)
                ));
            }
        }
        Dialect::SqlServer => {
            if !t.comment.is_empty() {
                out.push(sqlserver_comment(
                    &t.schema,
                    &t.name,
                    None,
                    &t.comment,
                    "sp_addextendedproperty",
                ));
            }
            for c in t.columns.iter().filter(|c| !c.comment.is_empty()) {
                out.push(sqlserver_comment(
                    &t.schema,
                    &t.name,
                    Some(&c.name),
                    &c.comment,
                    "sp_addextendedproperty",
                ));
            }
        }
        _ => {}
    }
    out
}

/// The body lines of `CREATE TABLE` (columns, then keys, foreign keys and checks).
fn body_lines(d: Dialect, t: &TableSpec, skip_fks: &[String]) -> Vec<String> {
    let rowid = (d == Dialect::Sqlite)
        .then(|| t.sqlite_rowid_pk())
        .flatten()
        .map(|c| c.name.clone());
    let mut lines: Vec<String> = t
        .columns
        .iter()
        .map(|c| column_def(d, c, rowid.as_deref() == Some(c.name.as_str())))
        .collect();
    if d == Dialect::ClickHouse {
        // ClickHouse has no key constraints; the primary key is part of the engine clause.
        for c in &t.checks {
            lines.push(check_clause(d, c));
        }
        return lines;
    }
    if let Some(pk) = t.primary_key.as_ref().filter(|k| !k.columns.is_empty()) {
        if rowid.is_none() {
            lines.push(pk_clause(d, pk));
        }
    }
    for k in t.unique_keys.iter().filter(|k| !k.columns.is_empty()) {
        lines.push(unique_clause(d, k));
    }
    for f in &t.foreign_keys {
        if !f.is_virtual && !skip_fks.contains(&f.name) {
            lines.push(fk_clause(d, f));
        }
    }
    for c in &t.checks {
        lines.push(check_clause(d, c));
    }
    lines
}

/// Table options after the closing parenthesis.
fn trailing_options(d: Dialect, t: &TableSpec) -> String {
    let o = &t.options;
    let mut parts = Vec::new();
    match d {
        Dialect::MySql => {
            if !o.engine.is_empty() {
                parts.push(format!("ENGINE = {}", o.engine));
            }
            if !o.charset.is_empty() {
                parts.push(format!("DEFAULT CHARSET = {}", o.charset));
            }
            if !o.collation.is_empty() {
                parts.push(format!("COLLATE = {}", o.collation));
            }
            if !t.comment.is_empty() {
                parts.push(format!("COMMENT = {}", d.quote_str(&t.comment)));
            }
        }
        Dialect::Postgres | Dialect::Oracle => {
            if !o.tablespace.is_empty() {
                parts.push(format!("TABLESPACE {}", d.quote_ident(&o.tablespace)));
            }
        }
        Dialect::Sqlite => {
            if o.without_rowid {
                parts.push("WITHOUT ROWID".into());
            }
            if o.strict {
                parts.push("STRICT".into());
            }
            return parts.join(", ");
        }
        Dialect::ClickHouse => {
            let engine = if o.engine.is_empty() {
                "MergeTree"
            } else {
                o.engine.as_str()
            };
            let engine = if engine.contains('(') {
                engine.to_string()
            } else {
                format!("{engine}()")
            };
            parts.push(format!("ENGINE = {engine}"));
            if !o.partition_by.is_empty() {
                parts.push(format!("PARTITION BY {}", o.partition_by));
            }
            let order = if !o.order_by.is_empty() {
                o.order_by.clone()
            } else {
                match t.primary_key.as_ref().map(|k| k.columns.as_slice()) {
                    Some([one]) => d.quote_ident(one),
                    Some(many) if !many.is_empty() => format!("({})", cols(d, many)),
                    _ => "tuple()".into(),
                }
            };
            if engine.contains("MergeTree") {
                parts.push(format!("ORDER BY {order}"));
            }
            if !t.comment.is_empty() {
                parts.push(format!("COMMENT {}", d.quote_str(&t.comment)));
            }
        }
        _ => {}
    }
    parts.join(" ")
}

/// `CREATE TABLE` of the dialog's table plus its indexes and comments, one statement per
/// entry. Foreign keys named in `skip_fks` are left out (added later by ALTER, for cycles).
pub fn create_statements(
    d: Dialect,
    t: &TableSpec,
    opts: CreateOptions,
    skip_fks: &[String],
) -> Vec<String> {
    let name = d.qualified(&t.schema, &t.name);
    let kind = match d {
        Dialect::Postgres if t.options.unlogged => "UNLOGGED TABLE",
        Dialect::Oracle if t.options.temporary => "GLOBAL TEMPORARY TABLE",
        _ if t.options.temporary => "TEMPORARY TABLE",
        _ => "TABLE",
    };
    let ine = if opts.if_not_exists && supports_if_not_exists(d, "table") {
        "IF NOT EXISTS "
    } else {
        ""
    };
    let lines = body_lines(d, t, skip_fks);
    let mut create = format!(
        "CREATE {kind} {ine}{name}\n(\n    {}\n)",
        lines.join(",\n    ")
    );
    let trailing = trailing_options(d, t);
    if !trailing.is_empty() {
        create.push(' ');
        create.push_str(&trailing);
    }
    create.push(';');
    if opts.if_not_exists && d == Dialect::SqlServer {
        create = format!(
            "IF OBJECT_ID({}, N'U') IS NULL\n{create}",
            d.quote_str(&name)
        );
    }
    let mut out = vec![create];
    if d != Dialect::ClickHouse {
        for i in &t.indexes {
            out.push(create_index(d, &t.name, &t.schema, i, opts.if_not_exists));
        }
    }
    out.extend(comment_statements(d, t));
    out
}

/// The Create Table preview: the statements joined as a script.
pub fn create_table(d: Dialect, t: &TableSpec, opts: CreateOptions) -> String {
    join(&create_statements(d, t, opts, &[]))
}

/// Statements as a script, a blank line between them.
pub fn join(statements: &[String]) -> String {
    let mut s = statements.join("\n\n");
    if !s.is_empty() {
        s.push('\n');
    }
    s
}

/// A foreign key added to an existing table.
pub fn add_foreign_key(d: Dialect, schema: &str, table: &str, f: &ForeignKey) -> String {
    format!(
        "ALTER TABLE {} ADD {};",
        d.qualified(schema, table),
        fk_clause(d, f)
    )
}

/// A table that references the dropped table (for Drop with cascade where the database
/// has no `CASCADE`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
pub struct Referencing {
    pub schema: String,
    pub table: String,
    pub constraint: String,
}

/// What Drop removes from the tree.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
pub struct DropRequest {
    pub schema: String,
    pub name: String,
    /// `table`, `view`, `matview`, `sequence`, `routine`, `index`, `trigger`, `type`.
    pub kind: String,
    /// The table of an index or trigger (MySQL and SQL Server need it).
    pub table: String,
    pub cascade: bool,
    pub if_exists: bool,
    /// Foreign keys of other tables that point at a dropped table.
    pub referencing: Vec<Referencing>,
}

/// `DROP …` of a tree object; with `cascade`, dependent objects go too (the dialect's
/// `CASCADE`, or the referencing foreign keys dropped first where there is none).
pub fn drop_statements(d: Dialect, r: &DropRequest) -> Vec<String> {
    let name = d.qualified(&r.schema, &r.name);
    let ie = if r.if_exists && d != Dialect::Oracle {
        "IF EXISTS "
    } else {
        ""
    };
    let mut out = Vec::new();
    let table_like = matches!(r.kind.as_str(), "table" | "view" | "matview");
    if r.cascade && table_like && !matches!(d, Dialect::Postgres | Dialect::Oracle) {
        for f in &r.referencing {
            if f.table.eq_ignore_ascii_case(&r.name) && f.schema.eq_ignore_ascii_case(&r.schema) {
                continue;
            }
            out.push(alter::drop_fk(d, &f.schema, &f.table, &f.constraint));
        }
    }
    let cascade = match (r.cascade, d) {
        (true, Dialect::Postgres) => " CASCADE",
        (true, Dialect::Oracle) if r.kind == "table" => " CASCADE CONSTRAINTS",
        _ => "",
    };
    let stmt = match r.kind.as_str() {
        "view" => format!("DROP VIEW {ie}{name}{cascade};"),
        "matview" => format!("DROP MATERIALIZED VIEW {ie}{name}{cascade};"),
        "sequence" => format!("DROP SEQUENCE {ie}{name}{cascade};"),
        "type" => format!("DROP TYPE {ie}{name}{cascade};"),
        "routine" | "function" => format!("DROP FUNCTION {ie}{name}{cascade};"),
        "procedure" => format!("DROP PROCEDURE {ie}{name};"),
        "index" => match d {
            Dialect::MySql => format!(
                "DROP INDEX {} ON {};",
                d.quote_ident(&r.name),
                d.qualified(&r.schema, &r.table)
            ),
            Dialect::SqlServer => format!(
                "DROP INDEX {ie}{} ON {};",
                d.quote_ident(&r.name),
                d.qualified(&r.schema, &r.table)
            ),
            _ => format!("DROP INDEX {ie}{name}{cascade};"),
        },
        "trigger" => match d {
            Dialect::Postgres => format!(
                "DROP TRIGGER {ie}{} ON {}{cascade};",
                d.quote_ident(&r.name),
                d.qualified(&r.schema, &r.table)
            ),
            _ => format!("DROP TRIGGER {ie}{name};"),
        },
        _ => format!("DROP TABLE {ie}{name}{cascade};"),
    };
    out.push(stmt);
    out
}

/// Rename a table (or view) from the tree.
pub fn rename_table(d: Dialect, schema: &str, from: &str, to: &str) -> String {
    alter::rename_table(d, schema, from, to)
}

/// Rename a column from the tree.
pub fn rename_column(d: Dialect, schema: &str, table: &str, from: &str, to: &str) -> String {
    alter::rename_column(d, schema, table, from, to)
}

