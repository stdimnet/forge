/// The abbreviation a snippet name stands for.
pub fn snippet(name: &str) -> Option<&'static str> {
    snippet_entry(name).map(|(_, v)| v)
}

/// `(name, abbreviation)` of a snippet.
pub fn snippet_entry(name: &str) -> Option<(&'static str, &'static str)> {
    SNIPPETS.iter().find(|(k, _)| *k == name).copied()
}

/// HTML elements that stay on the line of their siblings.
const INLINE: &[&str] = &[
    "a", "abbr", "acronym", "applet", "b", "basefont", "bdo", "big", "br", "button", "cite",
    "code", "del", "dfn", "em", "font", "i", "iframe", "img", "input", "ins", "kbd", "label",
    "map", "object", "q", "s", "samp", "select", "small", "span", "strike", "strong", "sub", "sup",
    "textarea", "tt", "u", "var", "video", "audio",
];

pub fn is_inline(name: &str) -> bool {
    INLINE.contains(&name.to_ascii_lowercase().as_str())
}

/// Elements without content or closing tag.
const VOID: &[&str] = &[
    "area", "base", "br", "col", "command", "embed", "hr", "img", "input", "keygen", "link",
    "meta", "param", "source", "track", "wbr",
];

pub fn is_void(name: &str) -> bool {
    VOID.contains(&name.to_ascii_lowercase().as_str())
}

