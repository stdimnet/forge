pub fn is_known_tag(name: &str) -> bool {
    TAGS.contains(&name) || snippet(name).is_some()
}

/// Tag of an element without a name (`.item`) inside `parent`.
pub fn implicit_tag(parent: &str) -> &'static str {
    match parent.to_ascii_lowercase().as_str() {
        "ul" | "ol" => "li",
        "table" | "tbody" | "thead" | "tfoot" => "tr",
        "tr" => "td",
        "select" | "optgroup" => "option",
        "audio" | "video" | "picture" => "source",
        "map" => "area",
        "colgroup" => "col",
        "dl" => "dt",
        p if is_inline(p) => "span",
        _ => "div",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_snippet_parses() {
        for (name, abbr) in SNIPPETS {
            assert!(crate::abbr::parse(abbr).is_ok(), "{name}: {abbr}");
        }
    }

    #[test]
    fn element_classes() {
        assert!(is_inline("A") && is_inline("span") && !is_inline("div"));
        assert!(is_void("img") && !is_void("div"));
        assert_eq!(implicit_tag("ul"), "li");
        assert_eq!(implicit_tag("em"), "span");
        assert_eq!(implicit_tag("section"), "div");
        assert!(is_known_tag("section") && is_known_tag("ul+") && !is_known_tag("const"));
    }
}
