//! Docker for .NET projects, like Rider's "Add Docker Support": a multi-stage Dockerfile
//! next to the project (built from the solution folder, so project references and
//! `Directory.*.props` are in the build context), a `.dockerignore`, and the `docker build`
//! / `docker run` command lines of the ".NET Docker" run configuration.

use std::collections::BTreeSet;

use forge_runtools::args::split_args;
use forge_runtools::Configuration;
use serde::{Deserialize, Serialize};

use crate::command::DotnetCommand;
use crate::msbuild::DotnetProject;
use crate::paths::{file_name, join, parent};
use crate::workspace::DotnetWorkspace;

/// The run configuration type that builds an image and runs it as a container.
pub const DOTNET_DOCKER: &str = "dotnet-docker";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedDocker {
    /// `src/Bookstore.Api/Dockerfile`.
    pub dockerfile_path: String,
    pub dockerfile: String,
    /// `.dockerignore` in the build context (the solution folder).
    pub dockerignore_path: String,
    pub dockerignore: String,
    /// The build context relative to the project root (`.`).
    pub context: String,
    /// `bookstore.api`.
    pub image: String,
    /// The container port of the application (`8080`).
    pub port: u16,
}

/// `net8.0` → `8.0`, `net9.0-windows` → `9.0`; older or unknown frameworks → `8.0`.
pub fn image_version(tfm: &str) -> String {
    let t = tfm.trim().to_ascii_lowercase();
    let v = t.strip_prefix("net").unwrap_or("");
    let v = v.split('-').next().unwrap_or("");
    match v.split_once('.') {
        Some((major, minor))
            if major.parse::<u32>().is_ok_and(|m| m >= 5) && minor.parse::<u32>().is_ok() =>
        {
            format!("{major}.{minor}")
        }
        _ => "8.0".into(),
    }
}

/// A Docker image name for a project (`Bookstore.Api` → `bookstore.api`).
pub fn image_name(project: &str) -> String {
    let n: String = project
        .to_ascii_lowercase()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '.' || c == '-' || c == '_' {
                c
            } else {
                '-'
            }
        })
        .collect();
    let n = n
        .trim_matches(|c: char| !c.is_ascii_alphanumeric())
        .to_string();
    if n.is_empty() {
        "app".into()
    } else {
        n
    }
}

/// The project and the projects it references, transitively, in a stable order.
fn closure<'a>(ws: &'a DotnetWorkspace, p: &'a DotnetProject) -> Vec<&'a DotnetProject> {
    let mut seen = BTreeSet::new();
    let mut out = Vec::new();
    let mut stack = vec![p];
    while let Some(x) = stack.pop() {
        if !seen.insert(x.path.clone()) {
            continue;
        }
        out.push(x);
        for r in &x.project_references {
            if let Some(dep) = ws.project(r) {
                stack.push(dep);
            }
        }
    }
    out.sort_by(|a, b| {
        (a.path != p.path)
            .cmp(&(b.path != p.path))
            .then_with(|| a.path.cmp(&b.path))
    });
    out
}

/// The Dockerfile and `.dockerignore` of a project. `root_files` are the files at the
/// project root (to copy `Directory.Build.props`, `Directory.Packages.props`,
/// `NuGet.config` and `global.json` before the restore).
pub fn generate(
    ws: &DotnetWorkspace,
    project: &str,
    port: Option<u16>,
    root_files: &[String],
) -> Result<GeneratedDocker, String> {
    let p = ws
        .project(project)
        .ok_or_else(|| format!("No project '{project}' in the solution"))?;
    if !p.is_runnable() {
        return Err(format!(
            "{} is a library; Docker support needs an application",
            p.name
        ));
    }
    let version = image_version(p.framework());
    let port = port.unwrap_or(8080);
    let runtime = if p.web { "aspnet" } else { "runtime" };
    let file = file_name(&p.path).to_string();
    let dir = parent(&p.path);
    let dll = format!("{}.dll", p.assembly_name);
    let mut d = String::new();
    d.push_str("# Generated by Forge for ");
    d.push_str(&p.name);
    d.push_str(". Build from the solution folder:\n");
    d.push_str(&format!(
        "#   docker build -f {} -t {} .\n\n",
        join(&dir, "Dockerfile"),
        image_name(&p.name)
    ));
    d.push_str(&format!(
        "FROM mcr.microsoft.com/dotnet/{runtime}:{version} AS base\n"
    ));
    d.push_str("USER $APP_UID\nWORKDIR /app\n");
    if p.web {
        d.push_str(&format!("EXPOSE {port}\n"));
        if port != 8080 {
            d.push_str(&format!("ENV ASPNETCORE_HTTP_PORTS={port}\n"));
        }
    }
    d.push('\n');
    d.push_str(&format!(
        "FROM mcr.microsoft.com/dotnet/sdk:{version} AS build\n"
    ));
    d.push_str("ARG BUILD_CONFIGURATION=Release\nWORKDIR /src\n");
    for f in [
        "Directory.Build.props",
        "Directory.Packages.props",
        "NuGet.config",
        "nuget.config",
    ] {
        if root_files.iter().any(|x| x == f) {
            d.push_str(&format!("COPY [\"{f}\", \"./\"]\n"));
        }
    }
    for x in closure(ws, p) {
        let xdir = parent(&x.path);
        let target = if xdir.is_empty() {
            "./".to_string()
        } else {
            format!("{xdir}/")
        };
        d.push_str(&format!("COPY [\"{}\", \"{target}\"]\n", x.path));
    }
    d.push_str(&format!("RUN dotnet restore \"{}\"\n", p.path));
    d.push_str("COPY . .\n");
    if !dir.is_empty() {
        d.push_str(&format!("WORKDIR \"/src/{dir}\"\n"));
    }
    d.push_str(&format!(
        "RUN dotnet build \"{file}\" -c $BUILD_CONFIGURATION -o /app/build\n\n"
    ));
    d.push_str("FROM build AS publish\nARG BUILD_CONFIGURATION=Release\n");
    d.push_str(&format!(
        "RUN dotnet publish \"{file}\" -c $BUILD_CONFIGURATION -o /app/publish /p:UseAppHost=false\n\n"
    ));
    d.push_str("FROM base AS final\nWORKDIR /app\nCOPY --from=publish /app/publish .\n");
    d.push_str(&format!("ENTRYPOINT [\"dotnet\", \"{dll}\"]\n"));
    Ok(GeneratedDocker {
        dockerfile_path: join(&dir, "Dockerfile"),
        dockerfile: d,
        dockerignore_path: ".dockerignore".into(),
        dockerignore: DOCKERIGNORE.into(),
        context: ".".into(),
        image: image_name(&p.name),
        port,
    })
}

const DOCKERIGNORE: &str = "**/.classpath
**/.dockerignore
**/.env
**/.git
**/.gitignore
**/.idea
**/.forge
**/.vs
**/.vscode
**/*.*proj.user
**/*.dbmdl
**/*.jfm
**/bin
**/obj
**/charts
**/docker-compose*
**/compose*
**/Dockerfile*
**/node_modules
**/npm-debug.log
**/secrets.dev.yaml
**/values.dev.yaml
LICENSE
README.md
";

/// The command lines of a ".NET Docker" configuration: `docker build` (run first, in the
/// Run tool window) and `docker run` (the configuration's process).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DockerCommands {
    pub build: DotnetCommand,
    pub run: DotnetCommand,
    pub image: String,
    pub container: String,
    /// The URL of the first published port (`http://localhost:8080`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
}

/// Options: `dockerfile`, `context` (`.`), `image`, `container`, `ports` (`8080:8080,
/// 8081:8081`), `env` (`KEY=VALUE` per line or `;`), `buildArgs`, `runArgs`, `docker`
/// (the CLI). Program arguments go after the image.
pub fn docker_commands(cfg: &Configuration) -> Result<DockerCommands, String> {
    let opt = |k: &str| cfg.option(k).trim().to_string();
    let dockerfile = opt("dockerfile");
    if dockerfile.is_empty() {
        return Err("Choose a Dockerfile".into());
    }
    let docker = if opt("docker").is_empty() {
        "docker".to_string()
    } else {
        opt("docker")
    };
    let context = if opt("context").is_empty() {
        ".".to_string()
    } else {
        opt("context")
    };
    let image = if opt("image").is_empty() {
        image_name(file_name(&parent(&dockerfile)))
    } else {
        opt("image")
    };
    let container = if opt("container").is_empty() {
        image.replace([':', '/', '.'], "-")
    } else {
        opt("container")
    };
    let mut build = vec![
        "build".to_string(),
        "-f".into(),
        dockerfile,
        "-t".into(),
        image.clone(),
    ];
    build.extend(split_args(&opt("buildArgs")));
    build.push(context);
    let mut run = vec![
        "run".to_string(),
        "--rm".into(),
        "--name".into(),
        container.clone(),
    ];
    let mut url = None;
    for p in opt("ports")
        .split([',', ' ', ';'])
        .map(str::trim)
        .filter(|p| !p.is_empty())
    {
        if url.is_none() {
            let host = p.split(':').next().unwrap_or(p);
            if host.chars().all(|c| c.is_ascii_digit()) {
                url = Some(format!("http://localhost:{host}"));
            }
        }
        run.extend(["-p".to_string(), p.to_string()]);
    }
    for e in opt("env")
        .split(['\n', ';'])
        .map(str::trim)
        .filter(|e| e.contains('='))
    {
        run.extend(["-e".to_string(), e.to_string()]);
    }
    for (k, v) in &cfg.options {
        if let Some(name) = k.strip_prefix("env.") {
            run.extend(["-e".to_string(), format!("{name}={v}")]);
        }
    }
    run.extend(split_args(&opt("runArgs")));
    run.push(image.clone());
    run.extend(split_args(&cfg.arguments));
    let cmd = |args: Vec<String>| DotnetCommand {
        program: docker.clone(),
        args,
        cwd: String::new(),
        env: Default::default(),
    };
    Ok(DockerCommands {
        build: cmd(build),
        run: cmd(run),
        image,
        container,
        url,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tests::{bookstore_files, fixture_reader};

    fn ws() -> DotnetWorkspace {
        crate::load_workspace(
            &bookstore_files(),
            &fixture_reader("bookstore"),
            "",
            "Debug",
        )
    }

    #[test]
    fn generates_a_multi_stage_dockerfile() {
        let g = generate(
            &ws(),
            "src/Bookstore.Api/Bookstore.Api.csproj",
            None,
            &[
                "Directory.Build.props".into(),
                "Directory.Packages.props".into(),
                "global.json".into(),
            ],
        )
        .unwrap();
        assert_eq!(g.dockerfile_path, "src/Bookstore.Api/Dockerfile");
        assert_eq!(g.image, "bookstore.api");
        let d = &g.dockerfile;
        assert!(
            d.contains("FROM mcr.microsoft.com/dotnet/aspnet:8.0 AS base\n"),
            "{d}"
        );
        assert!(d.contains("FROM mcr.microsoft.com/dotnet/sdk:8.0 AS build\n"));
        assert!(d.contains("COPY [\"Directory.Packages.props\", \"./\"]\n"));
        assert!(d.contains("COPY [\"src/Bookstore.Api/Bookstore.Api.csproj\", \"src/Bookstore.Api/\"]\nCOPY [\"src/Bookstore.Core/Bookstore.Core.csproj\", \"src/Bookstore.Core/\"]\n"));
        assert!(d.contains("WORKDIR \"/src/src/Bookstore.Api\"\n"));
        assert!(d.ends_with("ENTRYPOINT [\"dotnet\", \"Bookstore.Api.dll\"]\n"));
        assert!(g.dockerignore.contains("**/bin\n**/obj\n"));
        assert!(generate(&ws(), "src/Bookstore.Core/Bookstore.Core.csproj", None, &[]).is_err());
    }

    #[test]
    fn versions_and_names() {
        assert_eq!(image_version("net9.0"), "9.0");
        assert_eq!(image_version("net8.0-windows"), "8.0");
        assert_eq!(image_version("netstandard2.0"), "8.0");
        assert_eq!(image_name("My App"), "my-app");
    }

    #[test]
    fn command_lines() {
        let mut cfg = Configuration {
            name: "Api in Docker".into(),
            type_id: DOTNET_DOCKER.into(),
            ..Configuration::default()
        };
        cfg.options
            .insert("dockerfile".into(), "src/Bookstore.Api/Dockerfile".into());
        cfg.options
            .insert("ports".into(), "8080:8080, 8081:8081".into());
        cfg.options
            .insert("env".into(), "ASPNETCORE_ENVIRONMENT=Development".into());
        let c = docker_commands(&cfg).unwrap();
        assert_eq!(
            c.build.display(),
            "docker build -f src/Bookstore.Api/Dockerfile -t bookstore.api ."
        );
        assert_eq!(
            c.run.display(),
            "docker run --rm --name bookstore-api -p 8080:8080 -p 8081:8081 -e ASPNETCORE_ENVIRONMENT=Development bookstore.api"
        );
        assert_eq!(c.url.as_deref(), Some("http://localhost:8080"));
        assert!(docker_commands(&Configuration::default()).is_err());
    }
}
