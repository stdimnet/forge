// Project files (.sln / .csproj) for Forge. Unity's IDE packages generate them; this class
// asks the first one that is installed (Visual Studio Editor, JetBrains Rider Editor,
// Visual Studio Code Editor) through reflection, so Forge needs no generator of its own.

using System;
using System.IO;
using System.Linq;
using System.Reflection;
using UnityEditor;
using UnityEngine;

namespace Forge.Unity.Editor
{
    public static class ForgeProjectFiles
    {
        static readonly string[] Generators =
        {
            "Microsoft.Unity.VisualStudio.Editor.ProjectGeneration, Microsoft.Unity.VisualStudio.Editor",
            "Packages.Rider.Editor.ProjectGeneration.ProjectGeneration, JetBrains.Rider.Editor",
            "VSCodeEditor.ProjectGeneration, Unity.VSCode.Editor",
        };

        static readonly string[] CodeExtensions =
        {
            ".cs", ".shader", ".hlsl", ".cginc", ".compute", ".hlslinc", ".uss", ".uxml", ".asmdef",
            ".asmref", ".json", ".xml", ".txt", ".md", ".yaml", ".yml", ".inputactions", ".rsp",
        };

        /// <summary>Whether Forge should open the asset (code and text files; Unity opens the rest).</summary>
        public static bool IsCodeAsset(string path)
        {
            var ext = Path.GetExtension(path ?? "").ToLowerInvariant();
            return CodeExtensions.Contains(ext);
        }

        /// <summary>Whether changed assets need new project files.</summary>
        public static bool Affects(params string[][] lists)
        {
            return lists.Where(l => l != null).SelectMany(l => l).Any(p =>
            {
                var ext = Path.GetExtension(p).ToLowerInvariant();
                return ext == ".cs" || ext == ".asmdef" || ext == ".asmref" || ext == ".rsp" || ext == ".dll";
            });
        }

        /// <summary>Regenerate the project files with an installed IDE package's generator.</summary>
        public static bool Sync(out string message)
        {
            foreach (var name in Generators)
            {
                var type = Type.GetType(name, false);
                if (type == null)
                    continue;
                try
                {
                    var generator = Activator.CreateInstance(type);
                    var sync = type.GetMethod("Sync", BindingFlags.Public | BindingFlags.Instance, null, Type.EmptyTypes, null);
                    if (sync == null)
                        continue;
                    sync.Invoke(generator, null);
                    message = "Project files generated by " + type.Assembly.GetName().Name;
                    return true;
                }
                catch (Exception e)
                {
                    message = e.InnerException?.Message ?? e.Message;
                    Debug.LogWarning("Forge: generating project files failed: " + message);
                    return false;
                }
            }
            message = "Install com.unity.ide.visualstudio (Window > Package Manager) to generate project files.";
            return false;
        }

        /// <summary>Generate the project files when there are none.</summary>
        public static void SyncIfMissing()
        {
            var root = Path.GetDirectoryName(Application.dataPath);
            if (!Directory.GetFiles(root, "*.sln").Any())
                Sync(out _);
        }

        /// <summary>
        /// For batch mode: Unity -batchmode -quit -projectPath &lt;p&gt;
        /// -executeMethod Forge.Unity.Editor.ForgeProjectFiles.SyncFromCommandLine
        /// </summary>
        public static void SyncFromCommandLine()
        {
            var ok = Sync(out var message);
            Debug.Log("Forge: " + message);
            if (!ok)
                EditorApplication.Exit(1);
        }
    }
}
