//! The Android SDK location, as Android Studio finds it: the `android.sdk.path` setting,
//! `ANDROID_HOME`, `ANDROID_SDK_ROOT`, `sdk.dir` of the project's `local.properties`, then
//! the default folder of the platform (`~/Android/Sdk`, `~/Library/Android/sdk`,
//! `%LOCALAPPDATA%\Android\Sdk`). Forge never downloads the SDK; without one the UI shows
//! where to get it.

use std::path::{Path, PathBuf};

use serde::Serialize;

/// Where the SDK was found.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SdkLocation {
    pub path: PathBuf,
    /// `setting`, `ANDROID_HOME`, `ANDROID_SDK_ROOT`, `local.properties` or `default`.
    pub source: String,
}

/// What the SDK lookup may read: environment variables, the home folder and the platform.
pub struct SdkEnv<'a> {
    pub setting: &'a str,
    pub env: &'a dyn Fn(&str) -> Option<String>,
    pub local_properties: Option<&'a str>,
    pub home: Option<&'a Path>,
    /// `linux`, `macos` or `windows`.
    pub os: &'a str,
    /// Whether a folder looks like an SDK (it exists, with `platform-tools` or `platforms`).
    pub is_sdk: &'a dyn Fn(&Path) -> bool,
}

/// `sdk.dir` of a `local.properties` file (Java properties escapes: `C\:\\Android\\Sdk`).
pub fn local_properties_sdk_dir(text: &str) -> Option<String> {
    text.lines().find_map(|l| {
        let l = l.trim();
        if l.starts_with('#') || l.starts_with('!') {
            return None;
        }
        let (k, v) = l.split_once(['=', ':'])?;
        (k.trim() == "sdk.dir").then(|| unescape(v.trim()))
    })
}

fn unescape(v: &str) -> String {
    let mut out = String::new();
    let mut chars = v.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            if let Some(n) = chars.next() {
                out.push(n);
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// The default SDK folder of a platform.
pub fn default_sdk_dir(
    os: &str,
    home: Option<&Path>,
    env: &dyn Fn(&str) -> Option<String>,
) -> Option<PathBuf> {
    match os {
        "windows" => env("LOCALAPPDATA")
            .map(PathBuf::from)
            .or_else(|| home.map(|h| h.join("AppData").join("Local")))
            .map(|d| d.join("Android").join("Sdk")),
        "macos" => home.map(|h| h.join("Library/Android/sdk")),
        _ => home.map(|h| h.join("Android/Sdk")),
    }
}

/// Find the SDK: the first candidate that is one.
pub fn locate(e: &SdkEnv) -> Option<SdkLocation> {
    let mut candidates: Vec<(PathBuf, &str)> = Vec::new();
    if !e.setting.trim().is_empty() {
        candidates.push((PathBuf::from(e.setting.trim()), "setting"));
    }
    for var in ["ANDROID_HOME", "ANDROID_SDK_ROOT"] {
        if let Some(v) = (e.env)(var).filter(|v| !v.trim().is_empty()) {
            candidates.push((PathBuf::from(v.trim()), var));
        }
    }
    if let Some(dir) = e.local_properties.and_then(local_properties_sdk_dir) {
        candidates.push((PathBuf::from(dir), "local.properties"));
    }
    if let Some(d) = default_sdk_dir(e.os, e.home, e.env) {
        candidates.push((d, "default"));
    }
    candidates
        .into_iter()
        .find(|(p, _)| (e.is_sdk)(p))
        .map(|(path, source)| SdkLocation {
            path,
            source: source.to_string(),
        })
}

fn exe(name: &str, windows: bool) -> String {
    if windows {
        format!("{name}.exe")
    } else {
        name.to_string()
    }
}

/// `platform-tools/adb` of an SDK.
pub fn adb_path(sdk: &Path, windows: bool) -> PathBuf {
    sdk.join("platform-tools").join(exe("adb", windows))
}

/// `emulator/emulator` of an SDK.
pub fn emulator_path(sdk: &Path, windows: bool) -> PathBuf {
    sdk.join("emulator").join(exe("emulator", windows))
}

/// The hint shown without an SDK.
pub const NO_SDK_HINT: &str = "The Android SDK was not found. Install it with Android Studio or the command-line tools (developer.android.com/studio), then set ANDROID_HOME, sdk.dir in local.properties, or Settings | Languages & Frameworks | Android SDK. Forge does not download it.";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_properties() {
        let t = "## This file is automatically generated by Android Studio.\n#sdk.dir=/nope\nsdk.dir=C\\:\\\\Users\\\\me\\\\AppData\\\\Local\\\\Android\\\\Sdk\n";
        assert_eq!(
            local_properties_sdk_dir(t).as_deref(),
            Some("C:\\Users\\me\\AppData\\Local\\Android\\Sdk")
        );
        assert_eq!(
            local_properties_sdk_dir("sdk.dir = /opt/android-sdk").as_deref(),
            Some("/opt/android-sdk")
        );
        assert_eq!(local_properties_sdk_dir("ndk.dir=/x"), None);
    }

    #[test]
    fn lookup_order() {
        let env = |k: &str| match k {
            "ANDROID_SDK_ROOT" => Some("/opt/android-sdk".to_string()),
            _ => None,
        };
        let home = Path::new("/home/me");
        let existing = ["/opt/android-sdk", "/home/me/Android/Sdk", "/from/props"];
        let is_sdk = |p: &Path| existing.iter().any(|e| Path::new(e) == p);
        let mut e = SdkEnv {
            setting: "",
            env: &env,
            local_properties: Some("sdk.dir=/from/props"),
            home: Some(home),
            os: "linux",
            is_sdk: &is_sdk,
        };
        let l = locate(&e).unwrap();
        assert_eq!(
            (l.path.to_str().unwrap(), l.source.as_str()),
            ("/opt/android-sdk", "ANDROID_SDK_ROOT")
        );
        let none = |_: &str| None;
        e.env = &none;
        assert_eq!(locate(&e).unwrap().source, "local.properties");
        e.local_properties = None;
        let l = locate(&e).unwrap();
        assert_eq!(
            (l.path.to_str().unwrap(), l.source.as_str()),
            ("/home/me/Android/Sdk", "default")
        );
        e.setting = "/missing";
        e.home = None;
        assert!(locate(&e).is_none());
        assert_eq!(
            default_sdk_dir("macos", Some(home), &none).unwrap(),
            PathBuf::from("/home/me/Library/Android/sdk")
        );
        let win = |k: &str| (k == "LOCALAPPDATA").then(|| "C:/Users/me/AppData/Local".to_string());
        assert_eq!(
            default_sdk_dir("windows", None, &win).unwrap(),
            Path::new("C:/Users/me/AppData/Local")
                .join("Android")
                .join("Sdk")
        );
        assert_eq!(
            adb_path(Path::new("/sdk"), false),
            PathBuf::from("/sdk/platform-tools/adb")
        );
        assert_eq!(
            emulator_path(Path::new("/sdk"), true),
            PathBuf::from("/sdk/emulator/emulator.exe")
        );
    }
}
