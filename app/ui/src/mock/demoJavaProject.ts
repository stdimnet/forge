/** A completion item; methods insert their name with parentheses, like JDT LS. */
const item = (label: string, kind: string, detail: string): EditorCompletionItem => {
  const name = label.replace(/\(.*$/, "");
  return { label, kind, detail, insertText: kind === "method" ? `${name}()` : label, filterText: name, documentation: null };
};

