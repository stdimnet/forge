import { beforeEach, describe, expect, it } from "vitest";
import { invoke, listen } from "@/ipc";
import "./workspaceMock";
import type { DataSourceInfo } from "@/ipc/db";
import { defaultDumpRequest, defaultReadOptions, emptyTable, type DesignDialect, type DesignPreview, type ImportPreview, type ImportProgress, type ImportSummary, type ScriptResult, type TableSpec } from "@/ipc/dbObjects";
import { addDemoSources, addExplorerSources, resetDbMock } from "./dbMock";
import { statements } from "./dbObjectsMock";

const b64 = (text: string) => btoa(String.fromCharCode(...new TextEncoder().encode(text)));

async function shop(): Promise<DataSourceInfo> {
  const [ds] = await invoke<DataSourceInfo[]>("db_add_from_env");
  return ds;
}

describe("db objects mock", () => {
  beforeEach(() => resetDbMock());

  it("previews CREATE and ALTER through the Rust design code", async () => {
    const info = await invoke<DesignDialect>("db_design_info", { dialect: "postgres" });
    expect(info.types).toContain("jsonb");
    const t: TableSpec = { ...emptyTable("public", "tags"), columns: [{ name: "id", dataType: "bigint", nullable: false, comment: "", autoIncrement: true }], primaryKey: { name: "", columns: ["id"] } };
    const create = await invoke<DesignPreview>("db_design_preview", { dialect: "postgres", table: t });
    expect(create.sql).toContain('CREATE TABLE "public"."tags"');
    expect(create.sql).toContain("GENERATED BY DEFAULT AS IDENTITY");
    const old = { ...t, columns: t.columns.map((c) => ({ ...c, original: c.name })) };
    const next = { ...old, columns: [...old.columns, { name: "label", dataType: "text", nullable: true, comment: "", autoIncrement: false }] };
    const alter = await invoke<DesignPreview>("db_design_preview", { dialect: "postgres", old, table: next });
    expect(alter.statements).toEqual(['ALTER TABLE "public"."tags" ADD COLUMN "label" text;']);
  });

  it("loads a table for Modify Table with original column names", async () => {
    const ds = await shop();
    const spec = await invoke<TableSpec>("db_design_load", { id: ds.id, schema: "shop", table: "users" });
    expect(spec.columns[0].original).toBe(spec.columns[0].name);
    expect(spec.primaryKey?.columns).toEqual(["id"]);
  });

  it("checks scripts like the backend: read-only refused, production confirmed", async () => {
    addDemoSources();
    const prod = await invoke<{ confirm?: string }>("db_objects_guard", { id: "sales-prod", sql: "CREATE TABLE x (id int)" });
    expect(prod.confirm).toContain("production");
    await expect(invoke("db_run_script", { id: "sales-prod", sql: "DROP TABLE x" })).rejects.toThrow("production");
    const ok = await invoke<ScriptResult>("db_run_script", { id: "sales-prod", sql: "DROP TABLE x; DROP TABLE y", confirmed: true });
    expect(ok.executed).toBe(2);
    const ds = await shop();
    await invoke("db_data_source_save", { source: { ...ds, options: { ...ds.options, readOnly: true } } });
    await expect(invoke("db_run_script", { id: ds.id, sql: "ALTER TABLE users ADD COLUMN x int", confirmed: true })).rejects.toThrow("read-only");
    expect(statements("CREATE TABLE a (x text default 'a;b'); DROP TABLE b;")).toEqual(["CREATE TABLE a (x text default 'a;b')", "DROP TABLE b"]);
  });

  it("generates and formats DDL of the demo schema", async () => {
    addExplorerSources();
    const sql = await invoke<string>("db_generate_ddl", {
      id: "shop-pg",
      objects: [
        { schema: "public", kind: "table", name: "order_items" },
        { schema: "public", kind: "table", name: "orders" },
        { schema: "public", kind: "table", name: "users" },
      ],
      options: { includeDrops: true, ifNotExists: false, qualify: true },
    });
    const users = sql.indexOf('CREATE TABLE "public"."users"');
    const orders = sql.indexOf('CREATE TABLE "public"."orders"');
    const items = sql.indexOf('CREATE TABLE "public"."order_items"');
    expect(users).toBeGreaterThan(-1);
    expect(users).toBeLessThan(orders);
    expect(orders).toBeLessThan(items);
    expect(sql.indexOf("DROP TABLE IF EXISTS")).toBeLessThan(users);
  });

  it("previews and imports a CSV file with progress", async () => {
    const ds = await shop();
    const data = b64("id;name;joined\n1;Ada;2024-01-02\n2;\"Hopper; Grace\";2024-01-03\n3;Alan;\n");
    const pv = await invoke<ImportPreview>("db_import_preview", { source: { data }, options: defaultReadOptions(), rows: 2, dialect: "mysql" });
    expect(pv.table.delimiter).toBe(";");
    expect(pv.table.columns).toEqual(["id", "name", "joined"]);
    expect(pv.totalRows).toBe(3);
    expect(pv.table.rows).toHaveLength(2);
    expect(pv.guesses.map((g) => g.kind)).toEqual(["integer", "text", "date"]);
    expect(pv.types).toEqual(["bigint", "varchar(32)", "date"]);
    const events: ImportProgress[] = [];
    const un = await listen<ImportProgress>("db://import", (e) => events.push(e));
    const summary = await invoke<ImportSummary>("db_import_run", {
      id: ds.id,
      importId: "i1",
      source: { data },
      options: defaultReadOptions(),
      plan: { schema: "shop", table: "people", columns: [{ source: 0, target: "id", kind: "integer" }], create: null, batchSize: 2, onError: "skip", emptyAsNull: true, limit: 0 },
    });
    un();
    expect(summary.inserted).toBe(3);
    expect(events.map((e) => e.done)).toEqual([2, 3]);
    await expect(invoke("db_import_preview", { source: { path: "/tmp/x.csv" }, options: defaultReadOptions() })).rejects.toThrow("browser mode");
  });

  it("builds dump command lines and refuses restores on read-only sources", async () => {
    const ds = await shop();
    const tools = await invoke<{ tool: string }[]>("db_dump_tools", { id: ds.id });
    expect(tools.map((t) => t.tool)).toEqual(["mysqldump", "mysql"]);
    const cmd = await invoke<string>("db_dump_command", { id: ds.id, request: { ...defaultDumpRequest("mysqldump", "dump"), file: "/tmp/shop.sql" } });
    expect(cmd).toContain("mysqldump --host=");
    expect(cmd).toContain("--result-file=/tmp/shop.sql");
    expect(cmd).not.toContain("secret");
    expect(await invoke("db_restore_guard", { id: ds.id })).toBeNull();
    await invoke("db_data_source_save", { source: { ...ds, options: { ...ds.options, readOnly: true } } });
    await expect(invoke("db_restore_guard", { id: ds.id })).rejects.toThrow("read-only");
  });

  it("exports an Excel workbook", async () => {
    const b = await invoke<string>("db_export_xlsx", { sheet: "users", columns: ["id"], rows: [[1]] });
    expect(atob(b).slice(0, 2)).toBe("PK");
  });
});
