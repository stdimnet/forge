/** Comments, review threads and the comment editor. */
import { createSignal, For, Show } from "solid-js";
import { CircleCheck, FileCode, LoaderCircle, MessageSquare, Undo2 } from "lucide-solid";
import type { Discussion, Note } from "@/ipc/forges";
import { renderMarkdown } from "./markdown";
import { Avatar, ago, displayName } from "./ui";
import { caps } from "./store";

export function Markdown(props: { text: string; class?: string }) {
  return (
    <Show when={props.text.trim()} fallback={<div class={`fg-md muted ${props.class ?? ""}`}>No description provided.</div>}>
      <div class={`fg-md ${props.class ?? ""}`} innerHTML={renderMarkdown(props.text, caps().numberPrefix)} />
    </Show>
  );
}

export function NoteView(props: { note: Note; compact?: boolean }) {
  const n = () => props.note;
  return (
    <div class="fg-note" classList={{ compact: props.compact }}>
      <Avatar user={n().author} size={props.compact ? 20 : 24} />
      <div class="fg-note-body">
        <div class="fg-note-head">
          <span class="fg-note-author">{displayName(n().author)}</span>
          <span class="muted fg-small">{ago(n().createdAt)}</span>
        </div>
        <Markdown text={n().body} />
      </div>
    </div>
  );
}

/** A timeline event generated by the host ("approved these changes"). */
export function SystemNote(props: { note: Note }) {
  return (
    <div class="fg-system">
      <Avatar user={props.note.author} size={16} />
      <span class="fg-note-author">{displayName(props.note.author)}</span>
      <span class="muted">{props.note.body}</span>
      <span class="muted fg-small">· {ago(props.note.createdAt)}</span>
    </div>
  );
}

/** Text area with a submit button; Ctrl+Enter submits. */
export function CommentEditor(props: {
  placeholder: string;
  submitLabel: string;
  onSubmit: (body: string) => Promise<boolean>;
  onCancel?: () => void;
  autofocus?: boolean;
  rows?: number;
}) {
  const [text, setText] = createSignal("");
  const [busy, setBusy] = createSignal(false);
  const submit = async () => {
    const body = text().trim();
    if (!body || busy()) return;
    setBusy(true);
    try {
      if (await props.onSubmit(body)) setText("");
    } finally {
      setBusy(false);
    }
  };
  return (
    <div class="fg-editor">
      <textarea
        rows={props.rows ?? 3}
        placeholder={props.placeholder}
        value={text()}
        ref={(el) => props.autofocus && queueMicrotask(() => el.focus())}
        onInput={(e) => setText(e.currentTarget.value)}
        onKeyDown={(e) => {
          if (e.key === "Enter" && (e.ctrlKey || e.metaKey)) {
            e.preventDefault();
            void submit();
          } else if (e.key === "Escape" && props.onCancel) {
            e.stopPropagation();
            props.onCancel();
          }
        }}
      />
      <div class="fg-editor-actions">
        <span class="muted fg-small">Markdown supported · Ctrl+Enter to submit</span>
        <span class="spacer" />
        <Show when={props.onCancel}>
          <button class="btn-secondary" onClick={() => props.onCancel?.()}>
            Cancel
          </button>
        </Show>
        <button class="btn-primary" disabled={!text().trim() || busy()} onClick={() => void submit()}>
          <Show when={busy()}>
            <LoaderCircle size={13} class="spin" />
          </Show>
          {props.submitLabel}
        </button>
      </div>
    </div>
  );
}

/**
 * A review thread. `showLocation` adds the file and line (timeline); inside the diff the
 * thread sits under its line already.
 */
export function ThreadView(props: {
  discussion: Discussion;
  showLocation?: boolean;
  onReply: (body: string) => Promise<boolean>;
  onResolve?: (resolved: boolean) => Promise<void>;
  onOpenFile?: () => void;
}) {
  const d = () => props.discussion;
  const [collapsed, setCollapsed] = createSignal(props.discussion.resolved);
  const [replying, setReplying] = createSignal(false);
  const line = () => d().position?.newLine ?? d().position?.oldLine;
  return (
    <div class="fg-thread" classList={{ resolved: d().resolved }} data-thread={d().id}>
      <Show when={props.showLocation && d().position}>
        <div class="fg-thread-loc" onClick={() => props.onOpenFile?.()}>
          <FileCode size={13} />
          <span>{d().position!.path}</span>
          <span class="muted">:{line()}</span>
        </div>
      </Show>
      <Show
        when={!collapsed()}
        fallback={
          <button class="fg-thread-collapsed" onClick={() => setCollapsed(false)}>
            <CircleCheck size={13} />
            <span>Resolved thread</span>
            <span class="muted">
              · {d().notes.length} comment{d().notes.length === 1 ? "" : "s"} by {[...new Set(d().notes.map((n) => displayName(n.author)))].join(", ")}
            </span>
          </button>
        }
      >
        <div class="fg-thread-notes">
          <For each={d().notes}>{(n) => <NoteView note={n} compact />}</For>
        </div>
        <Show
          when={replying()}
          fallback={
            <div class="fg-thread-actions">
              <button class="fg-reply-btn" onClick={() => setReplying(true)}>
                <MessageSquare size={13} /> Reply
              </button>
              <span class="spacer" />
              <Show when={d().resolved}>
                <span class="fg-resolved-tag">
                  <CircleCheck size={12} /> Resolved
                </span>
              </Show>
              <Show when={props.onResolve && d().resolvable}>
                <button class="btn-secondary fg-small-btn" onClick={() => void props.onResolve!(!d().resolved)}>
                  <Show when={d().resolved} fallback={<CircleCheck size={13} />}>
                    <Undo2 size={13} />
                  </Show>
                  {d().resolved ? "Unresolve" : "Resolve"}
                </button>
              </Show>
            </div>
          }
        >
          <CommentEditor
            placeholder="Reply…"
            submitLabel="Reply"
            rows={2}
            autofocus
            onCancel={() => setReplying(false)}
            onSubmit={async (body) => {
              const ok = await props.onReply(body);
              if (ok) setReplying(false);
              return ok;
            }}
          />
        </Show>
      </Show>
    </div>
  );
}
