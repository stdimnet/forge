/** Cards of review mode: a pending review comment and an AI Review finding. */
import { createSignal, For, Show } from "solid-js";
import { CircleAlert, Info, MessageSquarePlus, Pencil, Sparkles, Trash2, TriangleAlert, X } from "lucide-solid";
import type { Draft, Finding, Severity } from "@/ipc/codeReview";
import { CommentEditor, Markdown } from "./Thread";

/** Text with `code` spans (titles and one-line summaries written by the model). */
export function InlineCode(props: { text: string; class?: string }) {
  return (
    <span class={`fg-inline-code ${props.class ?? ""}`}>
      <For each={props.text.split("`")}>{(part, i) => (i() % 2 ? <code>{part}</code> : part)}</For>
    </span>
  );
}

export const severityLabels: Record<Severity, string> = { error: "Error", warning: "Warning", info: "Note" };

export function SeverityIcon(props: { severity: Severity; size?: number }) {
  return (
    <span class={`fg-sev fg-sev-${props.severity}`} title={severityLabels[props.severity]}>
      <Show when={props.severity === "error"} fallback={<Show when={props.severity === "warning"} fallback={<Info size={props.size ?? 14} />}><TriangleAlert size={props.size ?? 14} /></Show>}>
        <CircleAlert size={props.size ?? 14} />
      </Show>
    </span>
  );
}

/** "Generated by <provider> · <model>": always shown under AI output. */
export function ProviderLine(props: { provider: string; model: string | null; prefix?: string }) {
  return (
    <div class="fg-ai-provider muted fg-small" data-ai-provider>
      <Sparkles size={11} />
      {props.prefix ?? "Generated by"} {props.provider}
      <Show when={props.model}> · {props.model}</Show>
    </div>
  );
}

/** A pending review comment; it is posted only when the review is submitted. */
export function DraftCard(props: { draft: Draft; onSave?: (d: Draft, body: string) => Promise<boolean>; onDelete?: (d: Draft) => void }) {
  const [editing, setEditing] = createSignal(false);
  const d = () => props.draft;
  return (
    <div class="fg-thread fg-draft" data-draft={d().id}>
      <div class="fg-draft-head">
        <span class="fg-pending-tag">Pending</span>
        <Show when={d().startLine}>
          <span class="muted fg-small">
            lines {d().startLine}–{d().position?.newLine ?? d().position?.oldLine}
          </span>
        </Show>
        <Show when={d().finding}>
          <span class="muted fg-small fg-draft-ai">
            <Sparkles size={11} /> from AI Review
          </span>
        </Show>
        <span class="spacer" />
        <Show when={props.onSave && !editing()}>
          <button class="icon-btn fg-tiny-btn" title="Edit" onClick={() => setEditing(true)}>
            <Pencil size={12} />
          </button>
        </Show>
        <Show when={props.onDelete}>
          <button class="icon-btn fg-tiny-btn" title="Delete" data-action="delete-draft" onClick={() => props.onDelete!(d())}>
            <Trash2 size={12} />
          </button>
        </Show>
      </div>
      <Show when={editing()} fallback={<Markdown text={d().body} />}>
        <CommentEditor
          placeholder="Comment…"
          submitLabel="Save"
          initial={d().body}
          rows={4}
          autofocus
          onCancel={() => setEditing(false)}
          onSubmit={async (body) => {
            const ok = await props.onSave!(d(), body);
            if (ok) setEditing(false);
            return ok;
          }}
        />
      </Show>
    </div>
  );
}

/** A finding of AI Review: nothing is posted unless the user turns it into a draft and submits. */
export function FindingCard(props: { finding: Finding; onAction?: (f: Finding, action: "draft" | "dismiss") => void; onOpen?: (f: Finding) => void; showLocation?: boolean }) {
  const f = () => props.finding;
  return (
    <div class={`fg-thread fg-finding fg-finding-${f().severity}`} data-finding={f().id}>
      <div class="fg-finding-head">
        <SeverityIcon severity={f().severity} />
        <InlineCode class="fg-finding-title" text={f().title || severityLabels[f().severity]} />
        <Show when={props.showLocation}>
          <button class="fg-finding-loc" title="Show in diff" onClick={() => props.onOpen?.(f())}>
            {f().path}
            <span class="muted">:{f().startLine ? `${f().startLine}–` : ""}{f().position?.newLine ?? f().line}</span>
          </button>
        </Show>
        <span class="spacer" />
        <span class="fg-ai-tag">
          <Sparkles size={11} /> AI
        </span>
      </div>
      <Markdown text={f().explanation} />
      <Show when={f().suggestion}>
        <div class="fg-suggestion">
          <div class="muted fg-small">Suggested change</div>
          <pre>{f().suggestion}</pre>
        </div>
      </Show>
      <Show when={!f().position}>
        <div class="muted fg-small">Line {f().line} is not part of the diff; the comment goes into the review body.</div>
      </Show>
      <Show when={props.onAction}>
        <div class="fg-thread-actions">
          <button class="btn-secondary fg-small-btn" data-action="finding-draft" onClick={() => props.onAction!(f(), "draft")}>
            <MessageSquarePlus size={13} />
            Add as Draft Comment
          </button>
          <button class="btn-secondary fg-small-btn" data-action="finding-dismiss" onClick={() => props.onAction!(f(), "dismiss")}>
            <X size={13} />
            Dismiss
          </button>
        </div>
      </Show>
    </div>
  );
}
