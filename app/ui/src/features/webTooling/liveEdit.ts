/**
 * Live Edit through the Browser Companion: saving a web file tells the paired browsers
 * (`companion_live_edit`), which swap style sheets in place (CSS hot swap) or reload the
 * pages that loaded the file. While typing in a style sheet the editor's text is pushed
 * after a short pause (`liveEdit.updateWhileTyping`), and CSS that File Watchers write
 * (Sass, Less) is pushed when it changes on disk. What a file means for the page is decided
 * in Rust (`forge_open::live_edit`).
 */
import { EditorView } from "@codemirror/view";
import { liveEditApi } from "@/ipc/webTooling";
import { registerEditorExtension } from "@/editor/extensions";
import { onFileSaved } from "@/state/editor";
import { onFsChanged } from "@/state/fsWatch";
import { getSetting } from "@/state/settings";

const enabled = () => getSetting<boolean>("liveEdit.enabled", true);
const isProjectFile = (path: string) => !path.includes("://") && !path.startsWith("forge:");
const isCss = (path: string) => /\.css$/i.test(path);

onFileSaved((path) => {
  if (!enabled() || !isProjectFile(path)) return;
  if (!isCss(path) && !getSetting<boolean>("liveEdit.reloadOnSave", true)) return;
  void liveEditApi.push(path).catch(() => undefined);
});

// Style sheets generated by watchers (app.scss -> app.css) and other external changes.
onFsChanged((c) => {
  if (!enabled()) return;
  for (const path of c.changed.filter(isCss)) void liveEditApi.push(path).catch(() => undefined);
});

registerEditorExtension(({ path }) => {
  if (!isCss(path) || !isProjectFile(path)) return null;
  let timer: ReturnType<typeof setTimeout> | undefined;
  return EditorView.updateListener.of((u) => {
    if (!u.docChanged || !enabled() || !getSetting<boolean>("liveEdit.updateWhileTyping", true)) return;
    clearTimeout(timer);
    const view = u.view;
    timer = setTimeout(() => void liveEditApi.push(path, view.state.doc.toString()).catch(() => undefined), getSetting<number>("liveEdit.delayMs", 400));
  });
});
