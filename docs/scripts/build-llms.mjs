#!/usr/bin/env node
/**
 * LLM-friendly documentation (https://llmstxt.org):
 *
 * - regenerates docs/llms-full.txt: every page of docs/guide/ as plain Markdown, frontmatter
 *   removed, in the reading order of the index pages (start page, then each section index and
 *   the pages it links, depth first), links rewritten to repository paths;
 * - checks that every link in the hand-written docs/llms.txt points to an existing file.
 *
 * No dependencies. Usage: node docs/scripts/build-llms.mjs [--check]  (`pnpm docs:llms` in app/ui).
 * With --check the script only verifies that llms-full.txt is up to date and llms.txt is valid.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, normalize, relative, resolve } from "node:path";

const docs = resolve(import.meta.dirname, "..");
const repo = resolve(docs, "..");
const guide = join(docs, "guide");
const checkOnly = process.argv.includes("--check");
const errors = [];

/** All Markdown files below `dir`. */
function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : name.endsWith(".md") ? [path] : [];
  });
}

/** Split a page into its frontmatter fields and body. */
function parse(path) {
  const text = readFileSync(path, "utf8");
  const match = text.match(/^---\n([\s\S]*?)\n---\n/);
  const fields = {};
  if (match) {
    for (const line of match[1].split("\n")) {
      const kv = line.match(/^(\w+):\s*(.*)$/);
      if (kv) fields[kv[1]] = kv[2].replace(/^"(.*)"$/, "$1");
    }
  }
  return { fields, body: match ? text.slice(match[0].length) : text };
}

/** Relative `.md` links of a page in order of appearance (code blocks and inline code skipped). */
function mdLinks(path, body) {
  const prose = body.replace(/```[\s\S]*?```/g, "").replace(/`[^`\n]*`/g, "");
  const out = [];
  for (const m of prose.matchAll(/\]\(([^)\s#]+\.md)(#[^)\s]*)?\)/g)) {
    if (/^[a-z]+:/.test(m[1])) continue;
    const target = normalize(join(dirname(path), m[1]));
    if (target.startsWith(guide) && existsSync(target)) out.push(target);
  }
  return out;
}

// ---- reading order: depth first through the index pages
const pages = walk(guide);
const order = [];
const seen = new Set();
function visit(path) {
  if (seen.has(path)) return;
  seen.add(path);
  order.push(path);
  if (!path.endsWith("index.md")) return;
  for (const target of mdLinks(path, parse(path).body)) {
    // Only follow links into this index's folder (its pages and sub-section indexes).
    if (target.startsWith(dirname(path))) visit(target);
  }
}
visit(join(guide, "index.md"));
for (const top of ["getting-started", "user", "reference", "developer"]) visit(join(guide, top, "index.md"));
for (const page of ["faq.md", "troubleshooting.md", "README.md"]) visit(join(guide, page));
// Pages no index links to: by folder, then by `order`.
const rest = pages
  .filter((p) => !seen.has(p))
  .sort((a, b) => dirname(a).localeCompare(dirname(b)) || Number(parse(a).fields.order ?? 999) - Number(parse(b).fields.order ?? 999));
for (const p of rest) visit(p);

/** Rewrite relative links and images of a page to repository paths. */
function rewrite(path, body) {
  return body.replace(/(!?\[[^\]]*\])\(([^)\s]+)\)/g, (all, label, href) => {
    if (/^([a-z]+:|#)/.test(href)) return all;
    const [file, anchor] = href.split("#");
    const abs = normalize(join(dirname(path), file));
    return `${label}(${relative(repo, abs).split("\\").join("/")}${anchor ? `#${anchor}` : ""})`;
  });
}

const parts = [
  "# Forge documentation (full text)\n",
  "> Forge is a PHPStorm-style IDE for Windows, Linux and macOS built with Rust + Tauri 2 and a SolidJS UI. " +
    "This file concatenates every page of the user and developer guide (docs/guide/) in reading order, " +
    "frontmatter removed and links rewritten to repository paths. Generated by docs/scripts/build-llms.mjs; do not edit.\n",
];
for (const path of order) {
  const { body } = parse(path);
  parts.push(`\n---\n\nSource: ${relative(repo, path).split("\\").join("/")}\n\n${rewrite(path, body).trim()}\n`);
}
const full = parts.join("\n");
const fullPath = join(docs, "llms-full.txt");
if (checkOnly) {
  if (!existsSync(fullPath) || readFileSync(fullPath, "utf8") !== full) errors.push("docs/llms-full.txt is out of date: run `pnpm docs:llms`");
} else {
  writeFileSync(fullPath, full);
  console.log(`wrote docs/llms-full.txt (${order.length} pages, ${Math.round(full.length / 1024)} KB)`);
}

// ---- check docs/llms.txt
const llms = readFileSync(join(docs, "llms.txt"), "utf8");
if (!/^# \S/.test(llms)) errors.push("docs/llms.txt must start with a `# Project name` heading");
if (!/^> \S/m.test(llms)) errors.push("docs/llms.txt needs a `> summary` blockquote");
let links = 0;
for (const m of llms.matchAll(/\]\(([^)\s]+)\)/g)) {
  const href = m[1];
  if (/^[a-z]+:/.test(href)) continue;
  links++;
  if (!existsSync(join(docs, href.split("#")[0]))) errors.push(`docs/llms.txt links to a missing file: ${href}`);
}

if (errors.length) {
  for (const e of errors) console.error(`error: ${e}`);
  process.exit(1);
}
console.log(`docs/llms.txt: ${links} links ok`);
